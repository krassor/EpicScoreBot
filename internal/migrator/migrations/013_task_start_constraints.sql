-- Ограничение "Начать не ранее" ролевой задачи диаграммы Ганта: нижняя
-- граница старта сверх уже существующих (очередь эпиков, порядок ролей
-- внутри стори, ручное смещение старта) — см.
-- openspec/changes/add-task-start-constraints/design.md, Решения 1 и 5.
--
-- Живёт в task_assignments (том же пользовательском вводе, что закрепление
-- исполнителя и смещение старта), а НЕ в gantt_tasks: строки диаграммы
-- удаляются и пересоздаются при каждой перегенерации, и ограничение
-- терялось бы — ровно тот дефект, что уже случился со смещением старта до
-- миграции 011_task_assignees и был исправлен переносом ввода сюда.
--
-- not_before_date — календарная дата, а не смещение (design.md Решение 5):
-- внешнее событие с известной датой не должно ехать при пересчёте дат самой
-- задачи или её стори.
ALTER TABLE task_assignments ADD COLUMN IF NOT EXISTS not_before_date DATE NULL;

-- wait_for_story_id/wait_for_role_id — ссылка на другую ролевую задачу
-- команды, адресуемая ТОЙ ЖЕ парой "стори (или эпик без сторей) + роль",
-- которой уже адресуется сама строка task_assignments (epic_id, role_id) —
-- design.md Решение 1. Оба поля задаются и снимаются только вместе
-- (проверяется на уровне сервиса, не в схеме).
--
-- ON DELETE SET NULL для обеих колонок: физическое удаление стори/роли,
-- на которую указывает ссылка, не должно ронять всю строку целиком (вместе
-- с not_before_date и остальным пользовательским вводом той же пары) — тот
-- же выбор, что уже сделан для user_id в этой таблице. В отличие от
-- временной недействительности ссылки (роль перестала оцениваться, эпик
-- вне периода — она обрабатывается планировщиком динамически, см.
-- design.md Решение 4), это необратимое исчезновение цели, и сохранять
-- нечитаемый "осколок" ссылки нет смысла.
ALTER TABLE task_assignments ADD COLUMN IF NOT EXISTS wait_for_story_id UUID NULL REFERENCES epics (id) ON DELETE SET NULL;
ALTER TABLE task_assignments ADD COLUMN IF NOT EXISTS wait_for_role_id UUID NULL REFERENCES roles (id) ON DELETE SET NULL;
