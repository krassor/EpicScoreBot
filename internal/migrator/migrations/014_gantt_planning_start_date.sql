-- Сохранённая дата планирования родительского бара эпика — источник нижней
-- границы расписания команды (teamFloor), не переписываемый пересчётом. До
-- этой миграции граница читала start_date родительской строки, которую сам
-- же пересчёт и переписывает при каждом вызове, — самоссылка: следующий
-- пересчёт узнавал границу из результата предыдущего, и расписание не могло
-- вернуться назад после снятия причины сдвига («храповик»). См.
-- openspec/changes/fix-team-floor-ratchet/design.md, Решение 1.
--
-- Заполняется один раз при генерации задач эпика (internal/gantt/
-- ganttService.go, generateTaskRowsForEpic) тем же значением, что seed-ит
-- start_date этой же строки. Родительская строка при каждой перегенерации
-- пересоздаётся (DeleteGanttTasksByEpicID + CreateGanttTask), поэтому
-- значение обновляется само собой — забыть его сбросить негде.
--
-- Для строк, существующих на момент миграции, остаётся NULL НАМЕРЕННО:
-- бэкафилл текущей (возможно, уже сдвинутой пересчётом) датой узаконил бы
-- накопленный сдвиг как «исходную» дату — дефект перестал бы
-- воспроизводиться, но расписание навсегда осталось бы уехавшим
-- (design.md Решение 2). До перегенерации такие эпики продолжают
-- участвовать в teamFloor по прежней формуле — читая start_date напрямую.
ALTER TABLE gantt_tasks ADD COLUMN IF NOT EXISTS planning_start_date DATE NULL;
